import { cssVar, type Theme, type Token } from './types.ts';

/** Tailwind v4 theme namespaces each token group maps to (`@theme inline`). */
const TAILWIND: Record<string, (name: string) => string | null> = {
	color: (n) => `--color-${n}`,
	type: (n) =>
		n.startsWith('font-')
			? `--font-${n.slice(5)}`
			: n.startsWith('text-')
				? `--text-${n.slice(5)}`
				: n.startsWith('leading-')
					? `--leading-${n.slice(8)}`
					: n.startsWith('weight-')
						? `--font-weight-${n.slice(7)}`
						: null,
	radius: (n) => `--radius-${n.slice(7)}`,
	space: () => null,
	motion: () => null,
	focus: () => null,
	size: () => null,
	depth: (n) => (n.startsWith('shadow-') ? `--shadow-${n.slice(7)}` : null)
};

const decl = (t: Token, theme: Theme) =>
	`\t${cssVar(t.name)}: ${typeof t.value === 'string' ? t.value : t.value[theme]};`;

/**
 * Generates the tokens stylesheet:
 * - light values on :root (the default), dark values under prefers-color-scheme: dark;
 * - [data-theme] overrides: the catalogue shows themes side by side, and the reader's Night
 *   setting applies night (spec 002);
 * - a Tailwind v4 `@theme inline` block so utilities resolve to the tokens, with Tailwind's
 *   default colour palette removed so only Longshelf colours exist.
 */
export function tokensToCss(tokens: Token[]): string {
	const themed = tokens.filter((t) => typeof t.value !== 'string');
	const fixed = tokens.filter((t) => typeof t.value === 'string');
	const block = (theme: Theme) => themed.map((t) => decl(t, theme)).join('\n');

	const themeLines = tokens
		.map((t) => {
			const tw = TAILWIND[t.group](t.name);
			return tw ? `\t${tw}: var(${cssVar(t.name)});` : null;
		})
		.filter(Boolean)
		.join('\n');

	return `/* Generated by apps/web/scripts/gen-tokens.ts from packages/shared/src/tokens. Do not edit. */

:root {
${fixed.map((t) => decl(t, 'light')).join('\n')}
${block('light')}
	color-scheme: light dark;
}

@media (prefers-color-scheme: dark) {
	:root {
${block('dark').replace(/^\t/gm, '\t\t')}
	}
}

[data-theme='light'] {
${block('light')}
	color-scheme: light;
}

[data-theme='dark'] {
${block('dark')}
	color-scheme: dark;
}

[data-theme='night'] {
${block('night')}
	color-scheme: dark;
}

@theme inline {
	--color-*: initial;
	--color-transparent: transparent;
	--color-current: currentColor;
${themeLines}
}
`;
}
